export const getFitnessTestGroup = (sportName: string, category: string = ""): typeof FITNESS_GROUPS[0] | null => {
  // Handle special cases based on category
  let groupId: number | null = null;
  const lowerCategory = category.toLowerCase();
  
  if (sportName === "กรีฑา") {
    if (lowerCategory.includes("ลาน") && (lowerCategory.includes("ทุ่ม") || lowerCategory.includes("พุ่ง") || lowerCategory.includes("ขว้าง"))) groupId = 6;
    else if (lowerCategory.includes("ลาน") && lowerCategory.includes("กระโดด")) groupId = 8;
    else if (lowerCategory.includes("ลาน")) groupId = 6;
    else if (lowerCategory.includes("ระยะสั้น")) groupId = 8;
    else if (lowerCategory.includes("ระยะกลาง") || lowerCategory.includes("ระยะไกล")) groupId = 9;
    else groupId = 8; // Default for Athletics
  }
  else if (sportName === "กีฬาทางน้ำ") {
    if (lowerCategory.includes("ระยะสั้น")) groupId = 7;
    else if (lowerCategory.includes("ระยะกลาง") || lowerCategory.includes("ระยะไกล")) groupId = 9;
    else groupId = 7; // Default for Aquatics
  } else {
    const foundGroup = FITNESS_GROUPS.find(g => g.sports.includes(sportName));
    if (foundGroup) groupId = foundGroup.id;
  }

  return groupId ? (FITNESS_GROUPS.find(g => g.id === groupId) || null) : null;
}
